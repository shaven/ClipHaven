import XCTest
@testable import ClipHavenCore

/// A pasteboard the test controls: each item is a type → bytes map.
final class FakePasteboard: PasteboardSource {
    var changeCount = 0
    var items: [[String: Data]] = []

    func set(_ items: [[String: Data]]) {
        self.items = items
        changeCount += 1
    }

    var itemTypes: [[String]] { items.map { Array($0.keys) } }
    func data(forType type: String, item: Int) -> Data? { items[item][type] }
}

final class ClipboardMonitorTests: XCTestCase {
    private var dir: URL!
    private var store: HistoryStore!
    private var board: FakePasteboard!
    private var monitor: ClipboardMonitor!

    override func setUpWithError() throws {
        dir = FileManager.default.temporaryDirectory.appendingPathComponent("ClipboardMonitorTests-\(UUID().uuidString)")
        try FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        store = try HistoryStore(url: dir.appendingPathComponent("history.sqlite"))
        board = FakePasteboard()
        monitor = ClipboardMonitor(source: board, store: store)
    }

    override func tearDownWithError() throws {
        monitor = nil
        store = nil
        try? FileManager.default.removeItem(at: dir)
    }

    private func latest() throws -> StoredClip? { try store.fetch(limit: 1).first }

    func testCapturesEveryClipMenuType() throws {
        for type in ClipType.allCases {
            let bytes = Data("payload for \(type)".utf8)
            board.set([[type.pasteboardType: bytes]])
            XCTAssertNotNil(try monitor.poll(), "\(type) was not captured")
            XCTAssertEqual(try latest()?.representations, [Representation(type: type.pasteboardType, data: bytes)], "\(type)")
        }
        XCTAssertEqual(try store.count(), ClipType.allCases.count)
    }

    func testCoversClipMenuEightTypes() {
        let names = Set(ClipType.allCases.map(\.clipMenuName))
        XCTAssertTrue(names.isSuperset(of: ["String", "RTF", "RTFD", "PDF", "TIFF", "PICT", "URL", "Filenames"]))
    }

    func testKeepsAllWantedTypesAndIgnoresOthers() throws {
        board.set([[
            "public.utf8-plain-text": Data("hello".utf8),
            "public.rtf": Data("{\\rtf1 hello}".utf8),
            "com.example.private-thing": Data("junk".utf8),
        ]])
        try monitor.poll()
        XCTAssertEqual(Set(try latest()?.representations.map(\.type) ?? []), ["public.utf8-plain-text", "public.rtf"])
    }

    func testSkipsMarkedClips() throws {
        for marker in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"] {
            board.set([["public.utf8-plain-text": Data("secret".utf8), marker: Data()]])
            XCTAssertNil(try monitor.poll(), marker)
        }
        XCTAssertEqual(try store.count(), 0)
    }

    func testSkipsMarkerOnAnyItem() throws {
        board.set([["public.utf8-plain-text": Data("a".utf8)], ["org.nspasteboard.ConcealedType": Data()]])
        XCTAssertNil(try monitor.poll())
    }

    func testIgnoresItsOwnWrites() throws {
        board.set([["public.utf8-plain-text": Data("mine".utf8), ClipboardMonitor.ownMarkerType: Data()]])
        XCTAssertNil(try monitor.poll())
        XCTAssertEqual(try store.count(), 0)
    }

    func testDoesNothingWhenUnchanged() throws {
        board.set([["public.utf8-plain-text": Data("once".utf8)]])
        XCTAssertNotNil(try monitor.poll())
        XCTAssertNil(try monitor.poll(), "same changeCount is not captured twice")
    }

    func testStartsFromCurrentChangeCount() throws {
        board.set([["public.utf8-plain-text": Data("before launch".utf8)]])
        let fresh = ClipboardMonitor(source: board, store: store)
        XCTAssertNil(try fresh.poll(), "what was on the clipboard at launch is not re-captured")
    }

    func testIgnoresClipsWithNoWantedType() throws {
        board.set([["com.example.private-thing": Data("x".utf8)]])
        XCTAssertNil(try monitor.poll())
    }

    func testCollectsAllFileURLs() throws {
        board.set([
            ["public.file-url": Data("file:///tmp/a.txt".utf8)],
            ["public.file-url": Data("file:///tmp/b.txt".utf8)],
        ])
        try monitor.poll()
        let clip = try XCTUnwrap(latest())
        XCTAssertEqual(clip.representations, [Representation(type: "public.file-url", data: Data("file:///tmp/a.txt\nfile:///tmp/b.txt".utf8))])
        XCTAssertEqual(clip.title, "a.txt, b.txt")
    }

    func testTitleIsFirstNonBlankLineTrimmedAndShortened() throws {
        board.set([["public.utf8-plain-text": Data("\n   first line here   \nsecond".utf8)]])
        try monitor.poll()
        XCTAssertEqual(try latest()?.title, "first line here")

        board.set([["public.utf8-plain-text": Data(String(repeating: "y", count: 200).utf8)]])
        try monitor.poll()
        XCTAssertEqual(try latest()?.title.count, ClipboardMonitor.maxTitleLength + 1, "shortened with an ellipsis")
    }

    func testTitleFallsBackToRTFTextThenTypeName() throws {
        board.set([["public.rtf": Data("{\\rtf1\\ansi rich words}".utf8)]])
        try monitor.poll()
        XCTAssertEqual(try latest()?.title, "rich words")

        board.set([["public.tiff": Data([1, 2, 3])]])
        try monitor.poll()
        XCTAssertEqual(try latest()?.title, "Image (TIFF)")
    }
}
