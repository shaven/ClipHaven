import AppKit

/// What the monitor needs from a pasteboard; `NSPasteboard` in the app, a fake in tests.
public protocol PasteboardSource: AnyObject {
    /// Bumps on every change to the pasteboard, as `NSPasteboard.changeCount` does.
    var changeCount: Int { get }
    /// The types on each pasteboard item.
    var itemTypes: [[String]] { get }
    func data(forType type: String, item: Int) -> Data?
}

/// Copies each new pasteboard change into history. macOS sends no change notification, so the
/// app calls `poll()` on a timer and this compares `changeCount`.
public final class ClipboardMonitor {
    /// Types that mark a clip as not for history (nspasteboard.org conventions).
    public static let skipMarkers: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
    ]
    /// Added to everything ClipHaven itself writes, so its own pastes are not re-captured.
    public static let ownMarkerType = "com.shavenconsulting.ClipHaven.own"
    public static let maxTitleLength = 60

    private let source: PasteboardSource
    private let store: HistoryStore
    private var lastChangeCount: Int

    public init(source: PasteboardSource, store: HistoryStore) {
        self.source = source
        self.store = store
        lastChangeCount = source.changeCount
    }

    /// Captures the pasteboard if it changed since the last poll; returns the stored clip's id.
    @discardableResult
    public func poll() throws -> Int64? {
        let count = source.changeCount
        guard count != lastChangeCount else { return nil }
        lastChangeCount = count

        let itemTypes = source.itemTypes
        let allTypes = Set(itemTypes.joined())
        guard allTypes.isDisjoint(with: Self.skipMarkers), !allTypes.contains(Self.ownMarkerType) else { return nil }

        var representations: [Representation] = []
        for type in ClipType.allCases where allTypes.contains(type.pasteboardType) {
            let items = itemTypes.indices.filter { itemTypes[$0].contains(type.pasteboardType) }
            if type == .filenames {
                // One line per file, so a multi-file copy is one clip.
                let lines = items.compactMap { source.data(forType: type.pasteboardType, item: $0) }
                    .compactMap { String(data: $0, encoding: .utf8) }
                guard !lines.isEmpty else { continue }
                representations.append(Representation(type: type.pasteboardType, data: Data(lines.joined(separator: "\n").utf8)))
            } else if let first = items.first, let data = source.data(forType: type.pasteboardType, item: first) {
                representations.append(Representation(type: type.pasteboardType, data: data))
            }
        }
        guard !representations.isEmpty else { return nil }
        return try store.insert(representations, title: Self.title(for: representations))
    }

    // MARK: - Titles

    static func title(for representations: [Representation]) -> String {
        func data(_ type: ClipType) -> Data? { representations.first { $0.type == type.pasteboardType }?.data }

        if let d = data(.string), let s = String(data: d, encoding: .utf8), let line = firstLine(s) { return line }
        if let d = data(.rtf), let s = NSAttributedString(rtf: d, documentAttributes: nil)?.string, let line = firstLine(s) { return line }
        if let d = data(.url), let s = String(data: d, encoding: .utf8), let line = firstLine(s) { return line }
        if let d = data(.filenames), let s = String(data: d, encoding: .utf8) {
            let names = s.split(separator: "\n").map { URL(string: String($0))?.lastPathComponent ?? String($0) }
            if let line = firstLine(names.joined(separator: ", ")) { return line }
        }
        let first = representations.compactMap { ClipType(pasteboardType: $0.type) }.first
        return first?.fallbackTitle ?? "Clip"
    }

    private static func firstLine(_ text: String) -> String? {
        guard let line = text.split(whereSeparator: \.isNewline)
            .map({ $0.trimmingCharacters(in: .whitespaces) })
            .first(where: { !$0.isEmpty }) else { return nil }
        return line.count > maxTitleLength ? String(line.prefix(maxTitleLength)) + "…" : line
    }
}
